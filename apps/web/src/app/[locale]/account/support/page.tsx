import { notFound } from 'next/navigation';
import { IdentityAccount } from '@/components/identity-account';
import { isLocale, text } from '@/lib/content';
import { serverIdentity } from '@/lib/identity-server';

type Props = { params: Promise<{ locale: string }> };

export async function generateMetadata({ params }: Props) {
  const { locale } = await params;
  if (!isLocale(locale)) notFound();
  return { title: text(locale, 'پشتیبانی', 'Support'), robots: { index: false, follow: false } };
}

export default async function Page({ params }: Props) {
  const { locale } = await params;
  if (!isLocale(locale)) notFound();
  return <IdentityAccount locale={locale} view="support" initial={await serverIdentity()}/>;
}
